let currentLang = localStorage.getItem('directbeam_lang') || 'en';

function applyTranslations(lang) {
  if (!translations[lang]) lang = 'en';
  currentLang = lang;
  localStorage.setItem('directbeam_lang', lang);

  // Set document direction for RTL languages (Arabic)
  document.documentElement.dir = (lang === 'ar') ? 'rtl' : 'ltr';

  const elements = document.querySelectorAll('[data-i18n]');
  elements.forEach(el => {
    const key = el.getAttribute('data-i18n');
    if (translations[lang][key]) {
      el.textContent = translations[lang][key];
    }
  });

  const langLabel = document.getElementById('current-lang-code');
  if (langLabel) {
    langLabel.textContent = lang.toUpperCase();
  }
}

document.addEventListener('DOMContentLoaded', () => {
  applyTranslations(currentLang);

  const langBtn = document.getElementById('lang-selector-btn');
  const langDropdown = document.getElementById('lang-dropdown-menu');

  if (langBtn && langDropdown) {
    langBtn.addEventListener('click', (e) => {
      e.stopPropagation();
      langDropdown.classList.toggle('hidden');
    });

    document.querySelectorAll('.lang-choice').forEach(item => {
      item.addEventListener('click', (e) => {
        const selected = item.getAttribute('data-lang');
        applyTranslations(selected);
        langDropdown.classList.add('hidden');
      });
    });

    document.addEventListener('click', () => {
      langDropdown.classList.add('hidden');
    });
  }
});